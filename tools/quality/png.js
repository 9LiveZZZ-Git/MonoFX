/* Minimal PNG writer + plotting primitives, so audio analysis can be LOOKED at.
   No dependencies: Node's zlib does the compression. Scalar summaries hide
   flutter, modal ringing and aliasing structure that a spectrogram shows at a
   glance — this exists so those can be inspected rather than inferred. */
'use strict';
const zlib=require('zlib'),fs=require('fs');

const CRC=(()=>{const t=new Int32Array(256);
  for(let n=0;n<256;n++){let c=n;for(let k=0;k<8;k++)c=c&1?0xEDB88320^(c>>>1):c>>>1;t[n]=c;}
  return (buf)=>{let c=-1;for(let i=0;i<buf.length;i++)c=t[(c^buf[i])&255]^(c>>>8);return (c^-1)>>>0;};})();

function chunk(type,data){
  const len=Buffer.alloc(4);len.writeUInt32BE(data.length,0);
  const td=Buffer.concat([Buffer.from(type,'ascii'),data]);
  const crc=Buffer.alloc(4);crc.writeUInt32BE(CRC(td),0);
  return Buffer.concat([len,td,crc]);
}

class Canvas{
  constructor(w,h,bg){
    this.w=w;this.h=h;
    this.px=Buffer.alloc(w*h*3);
    const [r,g,b]=bg||[18,20,24];
    for(let i=0;i<w*h;i++){this.px[i*3]=r;this.px[i*3+1]=g;this.px[i*3+2]=b;}
  }
  set(x,y,c){
    x|=0;y|=0;
    if(x<0||y<0||x>=this.w||y>=this.h)return;
    const o=(y*this.w+x)*3;this.px[o]=c[0];this.px[o+1]=c[1];this.px[o+2]=c[2];
  }
  hline(x0,x1,y,c){for(let x=x0;x<=x1;x++)this.set(x,y,c);}
  vline(x,y0,y1,c){for(let y=y0;y<=y1;y++)this.set(x,y,c);}
  line(x0,y0,x1,y1,c){
    const dx=Math.abs(x1-x0),dy=Math.abs(y1-y0);
    const sx=x0<x1?1:-1,sy=y0<y1?1:-1;let err=dx-dy,x=x0,y=y0;
    for(;;){this.set(x,y,c);
      if(x===x1&&y===y1)break;
      const e2=2*err;
      if(e2>-dy){err-=dy;x+=sx;}
      if(e2<dx){err+=dx;y+=sy;}}
  }
  rect(x0,y0,x1,y1,c){for(let y=y0;y<=y1;y++)this.hline(x0,x1,y,c);}
  // 5x7 bitmap font — enough for axis labels and titles
  text(x,y,s,c,scale){
    scale=scale||1;
    const F=Canvas.FONT;
    for(let i=0;i<s.length;i++){
      const g=F[s[i].toUpperCase()]||F['?'];
      if(g)for(let r=0;r<7;r++)for(let col=0;col<5;col++)
        if(g[r]&(1<<(4-col)))
          for(let a=0;a<scale;a++)for(let b=0;b<scale;b++)
            this.set(x+i*6*scale+col*scale+a,y+r*scale+b,c);
    }
  }
  save(path){
    const raw=Buffer.alloc(this.h*(this.w*3+1));
    for(let y=0;y<this.h;y++){
      raw[y*(this.w*3+1)]=0;
      this.px.copy(raw,y*(this.w*3+1)+1,y*this.w*3,(y+1)*this.w*3);
    }
    const ihdr=Buffer.alloc(13);
    ihdr.writeUInt32BE(this.w,0);ihdr.writeUInt32BE(this.h,4);
    ihdr[8]=8;ihdr[9]=2;ihdr[10]=0;ihdr[11]=0;ihdr[12]=0;
    fs.writeFileSync(path,Buffer.concat([
      Buffer.from([137,80,78,71,13,10,26,10]),
      chunk('IHDR',ihdr),
      chunk('IDAT',zlib.deflateSync(raw,{level:9})),
      chunk('IEND',Buffer.alloc(0))]));
    return path;
  }
}
