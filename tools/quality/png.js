// perceptual-ish colormap for spectrograms (dark -> blue -> green -> yellow -> white)
function heat(t){
  t=Math.max(0,Math.min(1,t));
  const stops=[[8,10,16],[20,40,110],[10,130,140],[120,200,70],[250,220,60],[255,255,255]];
  const s=t*(stops.length-1),i=Math.min(stops.length-2,Math.floor(s)),f=s-i;
  return [0,1,2].map(k=>Math.round(stops[i][k]+(stops[i+1][k]-stops[i][k])*f));
}
